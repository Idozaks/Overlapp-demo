/**
 * Synthetic Entity Generator Script
 * 
 * This script generates AI entities such as stores, websites, and physical locations
 * for testing purposes. All entities are clearly marked as synthetic/AI-generated.
 */

import { drizzle } from 'drizzle-orm/node-postgres';
import { Pool } from 'pg';
import * as schema from './shared/schema.ts';

// Create connection pool
const pool = new Pool({ connectionString: process.env.DATABASE_URL });
const db = drizzle(pool, { schema });

// Categories for our entities
const ENTITY_CATEGORIES = [
  'RETAIL',       // Physical stores
  'ONLINE',       // Websites and online platforms
  'EDUCATION',    // Educational institutions
  'HOSPITALITY',  // Hotels, restaurants, etc.
  'ENTERTAINMENT', // Theaters, parks, etc.
  'HEALTHCARE',   // Hospitals, clinics, etc.
];

// Generate a random AI-like name for our synthetic entities
function generateSyntheticName(category) {
  const prefixes = {
    'SYNTHETIC_RETAIL': ['AIShoppe', 'SynthMart', 'VirtualGoods', 'SimuStore', 'ByteBazaar'],
    'SYNTHETIC_ONLINE': ['DataFlow', 'CodeRealm', 'AlgoSite', 'NeuralWeb', 'BotPortal'],
    'SYNTHETIC_EDUCATION': ['LearnMatrix', 'SynthClass', 'AIAcademy', 'LogicSchool', 'DataCampus'],
    'SYNTHETIC_HOSPITALITY': ['PixelInn', 'BiteByte', 'SynthStay', 'AIResort', 'VirtualVenue'],
    'SYNTHETIC_ENTERTAINMENT': ['SimuCinema', 'BotTheater', 'AlgoArcade', 'VirtualVenue', 'SynthShow'],
    'SYNTHETIC_HEALTHCARE': ['DataMedical', 'AIClinic', 'SynthCare', 'VirtualHealth', 'BotMedicine'],
  };
  
  const suffixes = [
    'AI', 'Synth', 'Bot', 'Virtual', 'Sim', 'Tech', 'Bit', 'Byte', 'Net', 'Gen',
    'Matrix', 'Logic', 'Data', 'Pixel', 'Code', 'Algo', 'Neural', 'Digital'
  ];
  
  // Get a random prefix for the category
  const prefix = prefixes[category][Math.floor(Math.random() * prefixes[category].length)];
  
  // Sometimes add a suffix
  const shouldAddSuffix = Math.random() > 0.5;
  if (shouldAddSuffix) {
    const suffix = suffixes[Math.floor(Math.random() * suffixes.length)];
    return `${prefix} ${suffix}`;
  }
  
  return prefix;
}

