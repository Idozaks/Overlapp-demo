// Generate random coordinates for physical locations
function generateRandomCoordinates() {
  // Generate coordinates in reasonable ranges
  const latitude = (Math.random() * 180 - 90).toFixed(6);
  const longitude = (Math.random() * 360 - 180).toFixed(6);
  return { latitude, longitude };
}

// Generate synthetic content for an entity
function generateSyntheticContent(entityId, entityName, category) {
  const contentTypes = {
    'SYNTHETIC_RETAIL': ['product', 'promotion', 'event', 'review'],
    'SYNTHETIC_ONLINE': ['article', 'service', 'tool', 'community'],
    'SYNTHETIC_EDUCATION': ['course', 'program', 'resource', 'event'],
    'SYNTHETIC_HOSPITALITY': ['service', 'menu', 'room', 'event'],
    'SYNTHETIC_ENTERTAINMENT': ['show', 'event', 'attraction', 'experience'],
    'SYNTHETIC_HEALTHCARE': ['service', 'specialist', 'treatment', 'program'],
  };
  
  const contentType = contentTypes[category][Math.floor(Math.random() * contentTypes[category].length)];
  
  // Title templates
  const titleTemplates = {
    'product': [`New Product at ${entityName}`, `Featured Item: AI Product`, `Synthetic Product Showcase`],
    'promotion': [`Limited Time Offer at ${entityName}`, `Synthetic Promotion`, `AI-Generated Special`],
    'event': [`Upcoming Event at ${entityName}`, `Synthetic Event Announcement`, `AI-Generated Gathering`],
    'review': [`Customer Experience at ${entityName}`, `Synthetic Review`, `AI-Generated Feedback`],
    'article': [`Latest Article from ${entityName}`, `Synthetic Knowledge Base`, `AI-Generated Content`],
    'service': [`Services Offered by ${entityName}`, `Synthetic Service Spotlight`, `AI-Generated Offerings`],
    'tool': [`Tools Available at ${entityName}`, `Synthetic Utilities`, `AI-Generated Resources`],
    'community': [`Community at ${entityName}`, `Synthetic User Group`, `AI-Generated Network`],
    'course': [`Courses at ${entityName}`, `Synthetic Learning Path`, `AI-Generated Curriculum`],
    'program': [`Programs Offered by ${entityName}`, `Synthetic Educational Track`, `AI-Generated Study Plan`],
    'resource': [`Resources from ${entityName}`, `Synthetic Materials`, `AI-Generated Learning Aids`],
    'menu': [`Menu Items at ${entityName}`, `Synthetic Culinary Options`, `AI-Generated Dishes`],
    'room': [`Accommodations at ${entityName}`, `Synthetic Room Options`, `AI-Generated Stays`],
    'show': [`Shows at ${entityName}`, `Synthetic Performances`, `AI-Generated Entertainment`],
    'attraction': [`Attractions at ${entityName}`, `Synthetic Points of Interest`, `AI-Generated Exhibits`],
    'experience': [`Experiences at ${entityName}`, `Synthetic Adventures`, `AI-Generated Activities`],
    'specialist': [`Specialists at ${entityName}`, `Synthetic Practitioners`, `AI-Generated Experts`],
    'treatment': [`Treatments at ${entityName}`, `Synthetic Therapies`, `AI-Generated Care Options`],
  };
  
  const titles = titleTemplates[contentType] || [`${contentType.charAt(0).toUpperCase() + contentType.slice(1)} at ${entityName}`, `Synthetic ${contentType}`, `AI-Generated ${contentType}`];
  const title = titles[Math.floor(Math.random() * titles.length)];
  
  // Description templates
  const descriptionTemplates = [
    `This is a synthetic ${contentType} created for testing purposes. It represents a fictional ${contentType} that would be offered by ${entityName}.`,
    `An AI-generated ${contentType} for demonstration. This ${contentType} doesn't exist in the real world and is part of our synthetic data for ${entityName}.`,
    `A simulated ${contentType} created by AI to demonstrate how ${entityName} might present its offerings in a real-world scenario.`,
  ];
  
  const description = descriptionTemplates[Math.floor(Math.random() * descriptionTemplates.length)];
  
  // URL structure
  const url = `https://example.com/synthetic/${category.toLowerCase()}/${entityName.replace(/\s+/g, '-').toLowerCase()}/${contentType}`;
  
  // Thumbnail URL based on content type
  const thumbnailUrl = `https://source.unsplash.com/random/300x200/?${contentType},${category.split('_')[1].toLowerCase()}`;
  
  return {
    interestId: entityId,
    title,
    description,
    url,
    thumbnailUrl,
    type: contentType.toUpperCase(),
  };
}

// Create synthetic entities and their content
async function createSyntheticEntities() {
  console.log('Starting synthetic entity generation...');
  
  const createdEntities = [];
  const createdContent = [];
  
  try {
    // For each category, create 3-5 entities
    for (const category of ENTITY_CATEGORIES) {
      const numEntities = Math.floor(Math.random() * 3) + 3; // 3-5 entities per category
      
      console.log(`Creating ${numEntities} entities for category ${category}...`);
      
      for (let i = 0; i < numEntities; i++) {
        const entityName = generateSyntheticName(category);
        const entityDescription = generateSyntheticDescription(entityName, category);
        
        // Generate icon URL based on category
        const categoryBase = category.split('_')[1].toLowerCase();
        const iconUrl = `https://source.unsplash.com/random/100x100/?${categoryBase},icon`;
        
        try {
          // Insert the entity as an interest
          const [entity] = await db
            .insert(schema.interests)
            .values({
              name: entityName,
              category,
              description: entityDescription,
              iconUrl,
              isAiGenerated: true,
            })
            .returning();
          
          createdEntities.push(entity);
          console.log(`Created entity: ${entityName} (ID: ${entity.id})`);
          
          // Create 2-4 content items for each entity
          const numContentItems = Math.floor(Math.random() * 3) + 2; // 2-4 content items
          
          for (let j = 0; j < numContentItems; j++) {
            const contentData = generateSyntheticContent(entity.id, entityName, category);
            
            const [content] = await db
              .insert(schema.interestContent)
              .values(contentData)
              .returning();
            
            createdContent.push(content);
            console.log(`Created content: ${content.title} for entity ${entityName}`);
          }
        } catch (error) {
          console.error(`Error creating entity ${entityName}:`, error);
        }
      }
    }
    
    console.log(`Successfully created ${createdEntities.length} synthetic entities with ${createdContent.length} content items`);
    return { entities: createdEntities, content: createdContent };
    
  } catch (error) {
    console.error('Error in entity creation process:', error);
    throw error;
  }
}

// Call the function to create entities
createSyntheticEntities()
  .then((result) => {
    console.log('Entity generation complete!');
    console.log(`Created ${result.entities.length} entities and ${result.content.length} content items`);
    process.exit(0);
  })
  .catch((error) => {
    console.error('Failed to generate entities:', error);
    process.exit(1);
  });